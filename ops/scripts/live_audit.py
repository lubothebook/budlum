def load_ledger(root):
    path = os.path.join(root, LEDGER_PATH)
    with open(path, "r", encoding="utf-8") as handle:
        ledger = json.load(handle)
    for key in ("package", "tlg", "finding"):
        if key not in ledger:
            raise SystemExit("%s carries no %s table" % (LEDGER_PATH, key))
    return ledger


def summary(root, ledger):
    tree = Tree(root)
    packages = {p["id"]: measure_package(tree, p) for p in ledger["package"]}
    findings = [measure_finding(tree, f, packages) for f in ledger["finding"]]
    tlg = [measure_tlg(tree, item, findings) for item in ledger["tlg"]]
    return {
        "packages": {
            "total": len(ledger["package"]),
            "delivered_evidence_pending": sum(
                1 for p in ledger["package"]
                if packages[p["id"]]["state"] == "delivered, evidence pending"),
            "partial": sum(1 for p in ledger["package"]
                           if packages[p["id"]]["state"] == "partial"),
            "not_started": sum(1 for p in ledger["package"]
                               if packages[p["id"]]["state"] == "not started"),
        },
        "findings": {
            "total": len(findings),
            "critical": sum(1 for f in findings if f["severity"] == "Critical"),
            "high": sum(1 for f in findings if f["severity"] == "High"),
            "with_reproduction_test": 0,
        },
        "tlg": {
            "total": len(tlg),
            "green": sum(1 for t in tlg if t["state"] == "green"),
            "red": sum(1 for t in tlg if t["state"] == "red"),
            "unverifiable": sum(1 for t in tlg if t["state"] == "unverifiable"),
        },
        "gates": {
            "modules": len(tree.gate_modules()),
            "registered": len(tree.registered_gates()),
        },
    }


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Measure the delivery ledgers of the directive.")
    parser.add_argument("--root", default=".", help="repository root (default: .)")
    parser.add_argument("--write", action="store_true", help="regenerate the ledgers")
    parser.add_argument("--check", action="store_true", help="fail when a ledger is stale")
    parser.add_argument("--queue", action="store_true",
                        help="also measure the open pull request queue (needs gh and git)")
    parser.add_argument("--json", action="store_true", help="print the summary as JSON")
    args = parser.parse_args(argv)

    root = os.path.abspath(args.root)
    ledger = load_ledger(root)

    problems = structural_checks(root, ledger)
    if problems:
        for problem in problems:
            print("FAIL: " + problem, file=sys.stderr)
        return 1

    queue = queue_block(root, ledger) if args.queue else None
    docs = build_documents(root, ledger, queue)

    if args.write:
        written = write_documents(root, docs)
        for rel in written:
            print("wrote " + rel)
        if not written:
            print("no change: every ledger already matches the measurement")

    if args.check:
        problems += check_documents(root, docs)
        problems += placeholder_checks(root)
        problems += dash_checks(root)

    if args.json:
        print(json.dumps(summary(root, ledger), indent=2, sort_keys=True))

    if problems:
        for problem in problems:
            print("FAIL: " + problem, file=sys.stderr)
        return 1

    if args.check:
        print("OK: the ledgers match the measurement")
    return 0


if __name__ == "__main__":
    sys.exit(main())
