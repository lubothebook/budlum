SKIP_DIRS = {".git", "target", "node_modules", ".cargo"}

# A finding that has no closing package is a directive defect, not a delivery
# defect, and the table says so rather than guessing an owner.
NO_OWNER = "none recorded"

# The ledger carries the long state name once; a table cell carries a short one.
SHORT_STATE = {
    "delivered, evidence pending": "delivered, no CI verdict",
    "partial": "partial",
    "not started": "not started",
    "no lock path or test on the card": "nothing on the card",
    "record or document package": "record only",
    "not a package": "not a package",
}

# A card's "Lock paths" line mixes file paths with bare identifiers it also
# locks (`min_stake`, `VerifyInference`). A symbol is measured as a word in the
# tree, a path as a path; treating one as the other would report a lock as
# missing because it has no slash in it.
PATH_EXTENSIONS = (".rs", ".toml", ".md", ".json", ".yml", ".yaml", ".sol", ".proto",
                   ".bud", ".lock", ".txt", ".sh", ".py")


def expand_braces(spec):
    """`src/registry/{role,permissionless}.rs` becomes two paths."""
    match = re.search(r"\{([^{}]*)\}", spec)
    if not match:
        return [spec]
    out = []
    for option in match.group(1).split(","):
        out.extend(expand_braces(spec[:match.start()] + option + spec[match.end():]))
    return out


def is_path_spec(spec):
    return "/" in spec or spec.endswith(PATH_EXTENSIONS)


# --------------------------------------------------------------------------
# Reading the tree
# --------------------------------------------------------------------------
def walk(root):
    """Every file under `root`, as a repository-relative POSIX path, sorted."""
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            out.append(rel)
    return out


def read(root, rel, limit=None):
    path = os.path.join(root, rel)
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            return handle.read() if limit is None else handle.read(limit)
    except OSError:
        return None


def exists(root, rel):
    return os.path.exists(os.path.join(root, rel))


class Tree:
    """The answers a working tree can give about itself.

    Every index below is built in one pass over the files and kept, because a
    measurement that re-reads 470 000 lines once per question takes minutes and
    a measurement nobody runs is not a measurement.
    """

    TOKEN_RE = re.compile(r"\bfn\s+([a-zA-Z0-9_]+)\s*[(<]")
    WORD_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]{2,}")

    def __init__(self, root):
        self.root = root
        self.files = walk(root)
        self.rust = [f for f in self.files if f.endswith(".rs")]
        self._cache = {}
        self._fn_files = None

    def text(self, rel):
        if rel not in self._cache:
            self._cache[rel] = read(self.root, rel) or ""
        return self._cache[rel]

    def isfile(self, rel):
        return os.path.isfile(os.path.join(self.root, rel))

    def isdir(self, rel):
        return os.path.isdir(os.path.join(self.root, rel))

    def present(self, spec):
        """Does one lock path (or one evidence pointer) exist?

        A path is an exact file, an exact directory (written with or without a
        trailing slash) or a glob. Anything else is reported as absent, which
        is the safe direction: an absent path is a gap, a false present is a
        lie in the ledger.
        """
        spec = spec.strip().strip("`")
        if not spec:
            return False
        if any(ch in spec for ch in "*?["):
            import glob

            return bool(glob.glob(os.path.join(self.root, spec)))
        return self.isfile(spec) or self.isdir(spec.rstrip("/"))

    def fn_files(self):
        """Function name to the files that define it, in one pass."""
        if self._fn_files is None:
            index = {}
            for rel in self.rust:
                for name in set(self.TOKEN_RE.findall(self.text(rel))):
                    index.setdefault(name, []).append(rel)
            self._fn_files = index
        return self._fn_files

    def defines_fn(self, name):
        """Is there a `fn <name>` in the tree?

        The search is textual and deliberately narrow: `fn name(` or
        `fn name<`. A name that appears only in a string literal does not
        count, and a name that appears twice is not a duplicate: the ledger
        asks whether the test the card names exists, not how often.
        """
        return name in self.fn_files()

    def counts_fn(self, name):
        return len(self.fn_files().get(name, []))

    def defining_files(self, name):
        return list(self.fn_files().get(name, []))

    def tokens_present(self, names):
        """Which of these bare identifiers appear as a word anywhere in the tree.

        One pass, because a locked symbol such as `min_stake` is a name in the
        code, a manifest or a document, and the question is only whether the
        tree still carries it.
        """
        wanted = set(names)
        found = set()
        if not wanted:
            return found
        for rel in self.files:
            for word in self.WORD_RE.findall(self.text(rel)):
                if word in wanted:
                    found.add(word)
            if len(found) == len(wanted):
                break
        return found

    def gate_modules(self):
        """The gate modules `xtask/gates` carries, from the registry in main.rs."""
        text = self.text("xtask/gates/src/main.rs")
        return set(re.findall(r"pub mod ([a-z0-9_]+);", text))

    def registered_gates(self):
        """The gate names the runner registers, with their module."""
        text = self.text("xtask/gates/src/main.rs")
        return set(re.findall(r"run(?:_log|_args)?:\s*(?:Some\()?gates::([a-z0-9_]+)::", text))


# --------------------------------------------------------------------------
# Measuring the packages
# --------------------------------------------------------------------------
def measure_package(tree, package):
    paths = []
    symbols = []
    for spec in package.get("lock_paths", []):
        for expanded in expand_braces(spec.strip()):
            if is_path_spec(expanded):
                paths.append(expanded)
            elif expanded:
                symbols.append(expanded)
    paths_present = [p for p in paths if tree.present(p)]
    found_symbols = tree.tokens_present(symbols)
    symbols_present = [s for s in symbols if s in found_symbols]

    tests = package.get("card_tests", [])
    anywhere = [t for t in tests if tree.defines_fn(t)]
    owned = [t for t in tests
             if any(covered(rel, p) for rel in tree.defining_files(t) for p in paths)]
    return {
        "id": package["id"],
        "title": package.get("title", ""),
        "lane": package.get("lane", ""),
        "layer": package.get("layer", ""),
        "tlg": package.get("tlg", False),
        "depends_on": package.get("depends_on", []),
        "milestone": package.get("milestone", ""),
        "paths_total": len(paths),
        "paths_present": len(paths_present),
        "paths_missing": [p for p in paths if p not in paths_present],
        "symbols_total": len(symbols),
        "symbols_present": len(symbols_present),
        "symbols_missing": [s for s in symbols if s not in symbols_present],
        "tests_total": len(tests),
        "tests_present": len(anywhere),
        "tests_owned": len(owned),
        "tests_missing": [t for t in tests if t not in anywhere],
        "closes": package.get("closes", []),
        "state": package_state(len(paths), len(paths_present), len(tests),
                               len(anywhere), len(owned)),
    }


def covered(path, spec):
    """Is `path` inside the lock path `spec`? A file matches itself; a
    directory matches its subtree."""
    spec = spec.rstrip("/")
    return path == spec or path.startswith(spec + "/")


def package_state(paths_total, paths_present, tests_total, tests_present, tests_owned):
    if paths_total == 0 and tests_total == 0:
        return "no lock path or test on the card"
    if tests_total == 0:
        return "record or document package"
    if (tests_present == tests_total or tests_owned == tests_total) and \
            paths_present == paths_total:
        return "delivered, evidence pending"
    if paths_present or tests_present:
        return "partial"
    return "not started"


# --------------------------------------------------------------------------
# Measuring the findings
# --------------------------------------------------------------------------
def measure_finding(tree, finding, by_id):
    owners = finding.get("closes_with", [])
    owner_states = []
    for owner in owners:
        package = by_id.get(owner)
        owner_states.append((owner, package["state"] if package else "not a package"))
    locations = finding.get("locations", [])
    still = [loc for loc in locations if tree.present(loc)]
    if not locations:
        location_state = "not recorded"
    elif len(still) == len(locations):
        location_state = "recorded file present"
    elif still:
        location_state = "recorded file partly present"
    else:
        location_state = "recorded file gone"
    # The state a tree can prove is `unverified`: no reproduction test is
    # recorded against any of these rows yet, and section 14.1 item 5 makes
    # the test the first step of a closure. A row whose closing package is
    # fully delivered moves to `closure candidate`, which still needs the
    # red-to-green output of that test.
    if not owners:
        state = "unverified, no closing package recorded"
    elif all(s == "delivered, evidence pending" for _, s in owner_states):
        state = "closure candidate, reproduction test missing"
    else:
        state = "unverified"
    return {
        "id": finding["id"],
        "severity": finding.get("severity", "Unrecorded"),
        "family": finding.get("family", ""),
        "owners": owners,
        "owner_states": owner_states,
        "locations": locations,
        "location_state": location_state,
        "trace": finding.get("trace", ""),
        "state": state,
    }


