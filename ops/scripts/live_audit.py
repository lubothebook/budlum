def _test_match(tree, how, needle):
    """The test names of the tree that answer one probe selector."""
    names = []
    for name in tree.fn_files():
        if how == "suffix" and name.endswith(needle):
            names.append(name)
        elif how == "prefix" and name.startswith(needle):
            names.append(name)
        elif how == "contains" and needle in name:
            names.append(name)
        elif how == "exact" and name == needle:
            names.append(name)
    return sorted(set(names))


def measure_tlg(tree, item, findings):
    probe = TLG_PROBES.get(item["id"], {})
    evidence_bits = []
    missing = False

    if "files" in probe:
        for rel in probe["files"]:
            if tree.present(rel):
                evidence_bits.append("%s present" % rel)
            else:
                evidence_bits.append("%s absent" % rel)
                missing = True

    if "gates" in probe:
        modules = tree.gate_modules()
        registered = tree.registered_gates()
        for name in probe["gates"]:
            if name in modules and name in registered:
                evidence_bits.append("gate %s registered" % name)
            else:
                evidence_bits.append("gate %s absent" % name)
                missing = True

    if "tests" in probe:
        spec = probe["tests"]
        if isinstance(spec, list):
            found = [t for t in spec if tree.counts_fn(t)]
            for name in spec:
                if name in found:
                    evidence_bits.append("test %s present" % name)
                else:
                    evidence_bits.append("test %s absent" % name)
                    missing = True
        else:
            how, needle = spec
            names = _test_match(tree, how, needle)
            if names:
                evidence_bits.append("%d test(s) match %s" % (len(names), needle))
            else:
                evidence_bits.append("no test matches %s" % needle)
                missing = True

    if "finding_count" in probe or probe.get("kind") == "finding_count":
        severe = [f for f in findings if f["severity"] in ("Critical", "High")]
        closed = [f for f in findings if f["state"].startswith("closure candidate")]
        evidence_bits.append(
            "%d Critical or High finding(s), %d with a closure candidate"
            % (len(severe), len(closed))
        )
        missing = True

    if missing:
        state = "red"
    elif not evidence_bits:
        state = "unverifiable"
        evidence_bits.append("no probe is recorded for this item")
    else:
        state = "unverifiable"
        evidence_bits.append("the CI verdict and its run number are not in this tree")
    return {"id": item["id"], "requirement": item["requirement"], "asked": item["evidence"],
            "packages": item.get("packages", []), "state": state,
            "evidence": "; ".join(evidence_bits)}


