#!/usr/bin/env python3
"""The live delivery ledger.

The directive asks for four ledgers that no commit on `main` carries:

  * `docs/audit/LIVE_STATUS.md` (section 14.1 item 4, milestone M0): one row per
    finding, with its live state, its closing package and the file it was
    recorded against;
  * `docs/work/PACKAGES.md` (section 15.5 item 7): one row per work package,
    with its lane, its lock paths, its card and its state;
  * `docs/audit/TLG_REPORT.md` (section 18): one row per Testnet Launch Gate
    item, and an item without evidence is red (R-32);
  * `docs/audit/FINDINGS.md` (section 14.1 item 9): the ledger new findings are
    written to, starting at BLG-268.

The directive also fixes how a number enters a document: section 0.5 item 1
says an unmeasured number is not written. So the three generated ledgers are
not typed by hand. This script reads the snapshot in `config/audit/ledger.json`
(the identifiers of the directive's own tables, in English, because the
directive is not committed - section 0.1 item 5), measures the working tree,
and writes the tables. `--check` recomputes them and fails when the committed
file and the measurement disagree, which is what the `audit-ledgers` gate in
`xtask/gates` and the `Live ledgers` CI job call.

What it measures, and what it refuses to measure
------------------------------------------------

It measures what a working tree can answer:

  * whether a lock path of a package exists;
  * whether a test name printed on a package card exists as a function;
  * whether the file a finding was recorded against still exists;
  * whether the gate or the document a Testnet Launch Gate item names exists.

It refuses to turn any of that into a verdict. A test that exists is not a
test that passes, and a gate that is registered is not a gate that ran. So no
row says "green" on the strength of a file being present: rows say `red`,
`unverifiable`, or `delivered, evidence pending`. The CI run number and the
commit SHA that section 15.5 item 10 asks for come from a run, and a local
script has neither.

Exit status: 0 when every check passes, 1 when a check fails. `--write`
always exits 0 unless the snapshot itself is malformed.
"""

