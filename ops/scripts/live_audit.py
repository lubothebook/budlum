def cell(value):
    """One Markdown table cell, safe against pipes and newlines."""
    text = str(value).replace("|", "\\|").replace("\n", " ").strip()
    return text if text else "-"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(cell(c) for c in row) + " |")
    return out


def packages_block(root, ledger):
    tree = Tree(root)
    rows = [measure_package(tree, p) for p in ledger["package"]]
    lines = []
    counts = {"delivered, evidence pending": 0, "partial": 0, "not started": 0,
              "no lock path or test on the card": 0,
              "record or document package: no test on the card": 0}
    for row in rows:
        counts[row["state"]] = counts.get(row["state"], 0) + 1
    lines.append("Measured by `ops/scripts/live_audit.py`. %d packages, %d lock paths, "
                 "%d locked symbols and %d test names printed on the cards." % (
                     len(rows),
                     sum(r["paths_total"] for r in rows),
                     sum(r["symbols_total"] for r in rows),
                     sum(r["tests_total"] for r in rows)))
    lines.append("")
    lines.append("State counts: " + ", ".join(
        "%s %d" % (key, value) for key, value in sorted(counts.items()) if value) + ".")
    lines.append("")
    table_rows = []
    for row in rows:
        locks = "%d/%d" % (row["paths_present"], row["paths_total"])
        if row["symbols_total"]:
            locks += " + %d/%d symbol(s)" % (row["symbols_present"], row["symbols_total"])
        table_rows.append([
            row["id"],
            row["lane"],
            row["layer"],
            "yes" if row["tlg"] else "no",
            ", ".join(row["depends_on"]) if row["depends_on"] else "none",
            row["milestone"],
            locks,
            "%d/%d" % (row["tests_present"], row["tests_total"]),
            "%d/%d" % (row["tests_owned"], row["tests_total"]),
            len(row["closes"]),
            row["title"],
            row["state"],
        ])
    lines += table(["Package", "Lane", "Layer", "TLG", "Depends on", "Milestone",
                    "Lock paths present", "Card tests present", "Card tests in the "
                    "card's own paths", "Findings it closes", "Title", "State"],
                   table_rows)
    lines.append("")
    lines.append("A lock path count of 3/7 means four paths the card names do not exist. "
                 "A card test count of 0/4 means no function of that name is in the tree. "
                 "Neither number is a verdict: a present path can be a stub, and a present "
                 "test can fail. The verdict is a CI run, and section 15.5 item 10 keeps it "
                 "out of a sentence until the run exists.")
    return "\n".join(lines)


def live_block(root, ledger):
    tree = Tree(root)
    packages = {p["id"]: measure_package(tree, p) for p in ledger["package"]}
    rows = [measure_finding(tree, f, packages) for f in ledger["finding"]]
    by_severity = {}
    for row in rows:
        by_severity[row["severity"]] = by_severity.get(row["severity"], 0) + 1
    lines = []
    lines.append("Measured by `ops/scripts/live_audit.py`. %d findings: %d from the "
                 "finding ledger (BLG-001 to BLG-267) and %d archive records." % (
                     len(rows),
                     sum(1 for r in rows if r["family"] == "ledger"),
                     sum(1 for r in rows if r["family"] == "archive")))
    lines.append("")
    lines.append("Severity: " + ", ".join(
        "%s %d" % (key, by_severity[key]) for key in
        sorted(by_severity, key=lambda k: (-by_severity[k], k))) + ".")
    lines.append("")
    severe = [r for r in rows if r["severity"] in ("Critical", "High")]
    lines.append("%d of those are Critical or High, and the number of them with a "
                 "reproduction test in the tree is 0. Testnet Launch Gate item TLG-01 "
                 "therefore stays red and its verdict is in `docs/audit/TLG_REPORT.md`."
                 % len(severe))
    lines.append("")
    table_rows = []
    for row in rows:
        owners = ", ".join(
            "%s (%s)" % (owner, SHORT_STATE.get(state, state))
            for owner, state in row["owner_states"]
        ) if row["owners"] else NO_OWNER
        table_rows.append([
            row["id"],
            row["severity"],
            row["family"],
            owners,
            ", ".join(row["locations"]) if row["locations"] else "not recorded",
            row["location_state"],
            row["trace"] if row["trace"] else "-",
            row["state"],
        ])
    lines += table(["Finding", "Severity", "Source", "Closing package", "Recorded location",
                    "Location now", "Snapshot code trace", "Live state"], table_rows)
    lines.append("")
    lines.append("The `Snapshot code trace` column repeats the ratio the directive recorded "
                 "when it wrote the finding: how many of the identifiers in the finding's "
                 "evidence text were still in the analysis branch. It is a historical number "
                 "and it is not a status. The `Live state` column is what this tree can "
                 "prove, and it says `unverified` where no reproduction test exists, because "
                 "section 14.1 item 5 makes the test the first step of a closure.")
    return "\n".join(lines)


def tlg_block(root, ledger):
    tree = Tree(root)
    packages = {p["id"]: measure_package(tree, p) for p in ledger["package"]}
    findings = [measure_finding(tree, f, packages) for f in ledger["finding"]]
    rows = [measure_tlg(tree, item, findings) for item in ledger["tlg"]]
    green = sum(1 for r in rows if r["state"] == "green")
    red = sum(1 for r in rows if r["state"] == "red")
    unverifiable = sum(1 for r in rows if r["state"] == "unverifiable")
    lines = []
    lines.append("Measured by `ops/scripts/live_audit.py`. %d items: %d green, %d red, "
                 "%d unverifiable in this tree." % (len(rows), green, red, unverifiable))
    lines.append("")
    lines.append("An item is green only when its evidence exists and a CI run or a rehearsal "
                 "record says it passed. This script has neither, so an item whose evidence "
                 "exists is `unverifiable` here and not green. Section 18 makes an item "
                 "without evidence red, which is the other two states.")
    lines.append("")
    table_rows = []
    for row in rows:
        table_rows.append([
            row["id"],
            row["requirement"],
            row["asked"],
            ", ".join(row["packages"]) if row["packages"] else "every package",
            row["evidence"],
            row["state"],
        ])
    lines += table(["Item", "What has to be true", "Evidence the directive asks for",
                    "Source packages", "What this tree shows", "State"], table_rows)
    lines.append("")
    lines.append("No item is green. The sentence \"Budlum is ready for the testnet\" is "
                 "therefore not available (section 1.3, section 18).")
    return "\n".join(lines)


# --------------------------------------------------------------------------
# The queue measurement (needs git and gh; never part of --check)
# --------------------------------------------------------------------------
def _git(root, *args):
    try:
        out = subprocess.run(["git"] + list(args), cwd=root, capture_output=True,
                             text=True, check=False)
        return out.stdout.strip() if out.returncode == 0 else ""
    except OSError:
        return ""


def _gh_prs(root):
    try:
        out = subprocess.run(
            ["gh", "pr", "list", "--state", "open", "--limit", "200",
             "--json", "number,title,headRefName,baseRefName,additions,deletions,files"],
            cwd=root, capture_output=True, text=True, check=False)
    except OSError:
        return None
    if out.returncode != 0:
        return None
    try:
        return json.loads(out.stdout)
    except json.JSONDecodeError:
        return None


def queue_block(root, ledger):
    """The overlap between the open pull requests, measured with git.

    The GitHub API truncates a large pull request's file list, so the paths are
    read from `git diff` against the merge base instead. The API is used only
    for the number, the title and the head branch of each open pull request.
    """
    prs = _gh_prs(root)
    if prs is None:
        return None
    if not _git(root, "rev-parse", "--verify", "origin/main"):
        return None
    main_ref = "origin/main"

    claims = {}
    for pr in prs:
        for wp in re.findall(r"WP-(\d+)", pr.get("title", "")):
            claims.setdefault("WP-%02d" % int(wp), []).append(pr["number"])

    path_owners = {}
    added_by = {}
    orphans = []
    measured = 0
    for pr in sorted(prs, key=lambda item: item["number"]):
        head = pr.get("headRefName", "")
        if not head:
            continue
        revision = "origin/" + head
        if not _git(root, "rev-parse", "--verify", revision):
            continue
        base = _git(root, "merge-base", revision, main_ref)
        if not base:
            orphans.append(pr["number"])
            continue
        measured += 1
        diff = _git(root, "diff", "--name-status", "%s..%s" % (base, revision))
        for line in diff.split("\n"):
            if not line.strip():
                continue
            status, _, path = line.partition("\t")
            path_owners.setdefault(path, []).append(pr["number"])
            if status.startswith("A"):
                blob = _git(root, "rev-parse", "%s:%s" % (revision, path))
                added_by.setdefault(path, []).append((pr["number"], blob))

    shared = {path: owners for path, owners in path_owners.items() if len(owners) > 1}
    divergent = {}
    for path, entries in added_by.items():
        if len(entries) < 2:
            continue
        blobs = {blob for _, blob in entries}
        if len(blobs) > 1:
            divergent[path] = entries

    lines = []
    lines.append("Measured by `ops/scripts/live_audit.py --queue`. %d open pull requests, "
                 "%d of them comparable with `%s`, and no merge." % (
                     len(prs), measured, main_ref))
    lines.append("")
    lines.append("- Branches with no common ancestor with `%s`: %s." % (
        main_ref,
        ", ".join("#%d" % n for n in sorted(orphans)) if orphans else "none"))
    lines.append("- Paths two or more open pull requests change: %d." % len(shared))
    lines.append("- New files two or more pull requests add with different content: %d."
                 % len(divergent))
    lines.append("- Packages claimed by two or more open pull requests: %d." % sum(
        1 for owners in claims.values() if len(owners) > 1))
    lines.append("")
    lines.append("## New files implemented more than once")
    lines.append("")
    lines.append("The same path, added by two pull requests, with different bytes. One of "
                 "them is the implementation that would guard the tree, and which one is "
                 "decided by merge order rather than by review.")
    lines.append("")
    rows = []
    for path, entries in sorted(divergent.items(), key=lambda item: (-len(item[1]), item[0])):
        numbers = sorted(n for n, _ in entries)
        rows.append([path, len(numbers), ", ".join("#%d" % n for n in numbers)])
    lines += table(["Path", "Pull requests", "Which"], rows[:40])
    lines.append("")
    lines.append("## Packages claimed more than once")
    lines.append("")
    rows = [[wp, ", ".join("#%d" % n for n in sorted(claims[wp]))]
            for wp in sorted(claims) if len(claims[wp]) > 1]
    lines += table(["Package", "Open pull requests that claim it"], rows)
    lines.append("")
    lines.append("## The most shared paths")
    lines.append("")
    worst = sorted(shared.items(), key=lambda item: (-len(item[1]), item[0]))[:25]
    rows = [[path, len(owners), ", ".join("#%d" % n for n in sorted(owners))]
            for path, owners in worst]
    lines += table(["Path", "Open pull requests", "Which"], rows)
    lines.append("")
    lines.append("Resolution is the merge order plus section 15.3 item 6: one owner per "
                 "definition path. The listing above is the input to that decision, not the "
                 "decision. Nothing in this file closes a pull request or names a winner.")
    return "\n".join(lines)


