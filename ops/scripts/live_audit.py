def split_generated(text):
    """The (before, generated, after) three parts of a document."""
    if BEGIN not in text or END not in text:
        return None
    before, rest = text.split(BEGIN, 1)
    generated, after = rest.split(END, 1)
    return before, generated, after


def compose(header, block, footer=""):
    """One document, in the shape `--write` and `--check` both agree on."""
    text = "%s\n\n%s\n%s\n%s\n" % (
        header.rstrip("\n"), BEGIN, block.strip("\n"), END)
    if footer.strip():
        text += "\n%s\n" % footer.strip("\n")
    return text


def build_documents(root, ledger, queue):
    """The four (or five) documents this run produces."""
    docs = {
        PACKAGES_DOC: (PACKAGES_HEADER, packages_block(root, ledger)),
        LIVE_DOC: (LIVE_HEADER, live_block(root, ledger)),
        TLG_DOC: (TLG_HEADER, tlg_block(root, ledger)),
    }
    if queue:
        docs[QUEUE_DOC] = (CHECKPOINTS_HEADER, queue)
    return docs


def write_documents(root, docs):
    """Write every document; return the ones whose bytes changed.

    The renderer is idempotent on purpose: running `--write` twice must be a
    no-op the second time, or every run leaves a diff and a reader cannot tell a
    measurement from a whitespace change. An existing header and footer are kept
    as they are, so a hand-written paragraph above the block survives a rerun.
    """
    written = []
    for rel, (header, block) in sorted(docs.items()):
        current = read(root, rel)
        footer = ""
        if current is not None:
            parts = split_generated(current)
            if parts is not None:
                header, footer = parts[0], parts[2]
        new = compose(header, block, footer)
        if current != new:
            path = os.path.join(root, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(new)
            written.append(rel)
    return written


def check_documents(root, docs):
    problems = []
    for rel, (header, block) in sorted(docs.items()):
        current = read(root, rel)
        if current is None:
            problems.append("%s is missing; run --write" % rel)
            continue
        parts = split_generated(current)
        if parts is None:
            problems.append("%s carries no generated block markers" % rel)
            continue
        if parts[1].strip("\n") != block.strip("\n"):
            problems.append("%s does not match the measurement; run --write" % rel)
    return problems


