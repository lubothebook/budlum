def structural_checks(root, ledger):
    problems = []
    ids = [p["id"] for p in ledger["package"]]
    if len(ids) != 64 or len(set(ids)) != 64:
        problems.append("the snapshot must carry 64 unique package ids")
    for number in range(1, 65):
        if "WP-%02d" % number not in ids:
            problems.append("package WP-%02d is missing from the snapshot" % number)
    tlg = [t["id"] for t in ledger["tlg"]]
    if len(tlg) != 27 or len(set(tlg)) != 27:
        problems.append("the snapshot must carry 27 unique launch gate items")
    findings = [f["id"] for f in ledger["finding"]]
    if len(findings) != 311:
        problems.append("the snapshot must carry 311 findings, found %d" % len(findings))
    if len(set(findings)) != len(findings):
        problems.append("the snapshot carries a duplicate finding id")
    known = set(ids) | {"M0", "M1", "M2", "M3", "M4", "M5", "M6", "M7"}
    for package in ledger["package"]:
        for dep in package.get("depends_on", []):
            if dep not in known:
                problems.append("%s depends on %s, which is not a package or a milestone"
                                % (package["id"], dep))
    for finding in ledger["finding"]:
        for owner in finding.get("closes_with", []):
            if owner not in ids:
                problems.append("%s is closed by %s, which is not a package"
                                % (finding["id"], owner))
        if finding.get("severity") == "Unrecorded":
            problems.append("%s carries no severity" % finding["id"])
    return problems


PLACEHOLDERS = ("TODO", "TBD", "FIXME", "XXX", "???")


def placeholder_checks(root):
    problems = []
    for rel in (PACKAGES_DOC, LIVE_DOC, TLG_DOC, FINDINGS_DOC):
        text = read(root, rel)
        if text is None:
            problems.append("%s is missing" % rel)
            continue
        for token in PLACEHOLDERS:
            if token in text:
                problems.append("%s carries the placeholder %s" % (rel, token))
        if len(text) < 2000:
            problems.append("%s is too small to be a ledger (%d bytes)" % (rel, len(text)))
    return problems


def dash_checks(root):
    """The gate no_unicode_dashes rejects thirteen characters; the ledgers obey it."""
    banned = "\u2010\u2011\u2012\u2013\u2014\u2015\u2212\u00ad\u2e3a\u2e3b\ufe58\ufe63\uff0d"
    problems = []
    for rel in (PACKAGES_DOC, LIVE_DOC, TLG_DOC, FINDINGS_DOC):
        text = read(root, rel) or ""
        for ch in banned:
            if ch in text:
                problems.append("%s carries U+%04X, which the dash gate rejects"
                                % (rel, ord(ch)))
    return problems


